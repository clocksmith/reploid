// Writes the Dart view of the requester contract and the model catalog.
//
// The contract (packages/reploid/contracts/requester/requester-contract.json)
// and the catalog (shared/config/chat-models.json) at the repository root are
// the only definitions. This tool copies their values into Dart so no constant
// or message name is typed by hand in the app. Run with --check to fail when
// the committed output is stale.
import 'dart:convert';
import 'dart:io';

const _contractPath =
    '../../packages/reploid/contracts/requester/requester-contract.json';
const _catalogPath = '../../shared/config/chat-models.json';
const _output = 'app/lib/infrastructure/reploid_api/contract.g.dart';

String _lit(Object? value) => switch (value) {
  String() =>
    "'${value.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'",
  _ => '$value',
};

String _camel(String text) {
  final parts = text.split(RegExp('[^A-Za-z0-9]+')).where((p) => p.isNotEmpty);
  final joined = parts.map((p) => p[0].toUpperCase() + p.substring(1)).join();
  return joined[0].toLowerCase() + joined.substring(1);
}

String render(Map<String, Object?> contract, Object? catalog) {
  final constants = contract['constants']! as Map<String, Object?>;
  final signaling = constants['signaling']! as Map<String, Object?>;
  final rtc = constants['rtc']! as Map<String, Object?>;
  final generation = constants['generation']! as Map<String, Object?>;
  final ids = generation['schemaIds']! as Map<String, Object?>;
  final objects = contract['objects']! as Map<String, Object?>;
  final receipt = objects['receiptV2']! as Map<String, Object?>;
  final envelope = contract['envelope']! as Map<String, Object?>;
  final channel = contract['channelMessages']! as Map<String, Object?>;
  final frames = contract['signalingMessages']! as Map<String, Object?>;
  final rows = (catalog is Map ? catalog['models'] : catalog)! as List<Object?>;
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_contract.dart. Do not edit.')
    ..writeln(
      '// Sources: packages/reploid/contracts/requester/'
      'requester-contract.json',
    )
    ..writeln('// and shared/config/chat-models.json at the repository root.')
    ..writeln('// dart format off')
    ..writeln()
    ..writeln('/// Constants of the requester contract.')
    ..writeln('abstract final class Contract {')
    ..writeln('  static const schema = ${_lit(contract['schema'])};');
  void group(String prefix, Map<String, Object?> values, List<String> keys) {
    for (final key in keys) {
      if (!values.containsKey(key)) {
        throw StateError('The contract no longer has $prefix.$key');
      }
      out.writeln(
        '  static const ${_camel('$prefix ${key}')} = ${_lit(values[key])};',
      );
    }
  }

  group('signaling', signaling, [
    'publicUrl',
    'publicRoomId',
    'publicJoinToken',
    'defaultNativeOrigin',
    'heartbeatMs',
    'connectTimeoutMs',
    'reconnectBaseMs',
    'reconnectMaxMs',
    'maxFrameBytes',
    'tokenMinLength',
  ]);
  group('rtc', rtc, [
    'channelLabel',
    'ordered',
    'envelopeProtocolVersion',
    'maxPayloadSize',
    'sendBufferLimitBytes',
    'pingIntervalMs',
    'peerSilenceMs',
  ]);
  final ice = [
    for (final server in rtc['iceServers']! as List<Object?>)
      (server! as Map<String, Object?>)['urls'],
  ];
  out.writeln(
    '  static const rtcIceServerUrls = '
    '[${ice.map(_lit).join(', ')}];',
  );
  group('generation', generation, [
    'timeoutMs',
    'discoveryTimeoutMs',
    'identityProtocol',
    'admissionProtocol',
    'offerId',
    'backend',
  ]);
  for (final entry in ids.entries) {
    out.writeln(
      '  static const ${_camel('id ${entry.key}')} = '
      '${_lit(entry.value)};',
    );
  }
  out
    ..writeln(
      '  static const receiptSignedFields = '
      '[${(receipt['x-signedPayloadFields']! as List<Object?>).map(_lit).join(', ')}];',
    )
    ..writeln(
      '  static const knownTypes = '
      '{${(envelope['x-knownTypes']! as List<Object?>).map(_lit).join(', ')}};',
    )
    ..writeln('}')
    ..writeln()
    ..writeln('/// Data-channel message types the contract defines.')
    ..writeln('abstract final class ChannelType {');
  for (final type in channel.keys) {
    out.writeln(
      '  static const ${_camel(type.replaceFirst('reploid:', ''))} = '
      '${_lit(type)};',
    );
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('/// Signaling frame types the contract defines.')
    ..writeln('abstract final class SignalingType {');
  for (final type in frames.keys) {
    out.writeln('  static const ${_camel(type)} = ${_lit(type)};');
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('/// One row of the shared model catalog.')
    ..writeln('final class CatalogRow {')
    ..writeln(
      '  const CatalogRow({required this.id, required this.identity, '
      'required this.name});',
    )
    ..writeln('  final String id;')
    ..writeln('  final String identity;')
    ..writeln('  final String name;')
    ..writeln('}')
    ..writeln()
    ..writeln(
      '/// Models that a whole computer on the network can answer '
      'with.',
    )
    ..writeln('const modelCatalog = [');
  for (final row in rows.cast<Map<String, Object?>>()) {
    if (row['id'] is! String || row['identity'] is! String) continue;
    out.writeln(
      '  CatalogRow(id: ${_lit(row['id'])}, '
      'identity: ${_lit(row['identity'])}, '
      'name: ${_lit(row['name'] ?? row['id'])}),',
    );
  }
  out.writeln('];');
  return out.toString();
}

void main(List<String> arguments) {
  final contract = jsonDecode(
    File(_contractPath).readAsStringSync(),
  ) as Map<String, Object?>;
  final catalog = jsonDecode(File(_catalogPath).readAsStringSync());
  final text = render(contract, catalog);
  final file = File(_output);
  if (arguments.contains('--check')) {
    if (!file.existsSync() || file.readAsStringSync() != text) {
      stderr.writeln(
        '$_output is stale. Run: dart run tool/generate_contract.dart',
      );
      exitCode = 1;
      return;
    }
    stdout.writeln('Contract constants are current.');
    return;
  }
  file.writeAsStringSync(text);
  stdout.writeln('Wrote $_output');
}
