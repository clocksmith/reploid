// Copy of ../final-4/check-disclosure-files.js for final-6, which spans base 95641fe7 to cec3ff6b
// (100 changed files) instead of one commit. Differences:
//  A. self/config/module-inventory.json and self/config/vfs-manifest.json are rebuilt by the export
//     pipeline (build-module-inventory, build-vfs-manifest after staging), so their served copies are
//     compared with the export's own regenerated self/config copies, not the commit blobs.
//  B. The product session now opens ordered requester history (5327eed3): the check requires the one
//     requesterIdentity port to be defined from swarm.partitions and passed on every opening path,
//     instead of the single final-4 call string. The two-stage canonical configuration's opening
//     (`canonical,` with canonical.participantId) is exempt and recorded: its participant is the
//     authenticated swarm peer itself, unchanged since final-4.
// Checks where the application files changed by one commit appear in the produced deliveries,
// and that each served or packaged copy equals the commit's file. New script for final-4;
// reads files and commit blobs only.
//  - Served: a `self/<path>` file is served at `<path>` in the hosting payload when the export's
//    browser descriptor lists it (declaration files are not served).
//  - `self/vendor/reploid/package-assets.json` is regenerated by the export pipeline (its three
//    Doppler contract entries follow the 0.6.28 pin), so it is compared entry by entry: every
//    entry for a changed vendored file must carry the commit's hash and size.
//  - Packaged: any changed path is looked up at the same path in the installed native package
//    and in its descriptor; absence is recorded, not treated as a failure.
//  - The served product session must pass `requesterIdentity` to the chat session.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';

const [applicationRoot, installedRoot, previousApplicationRoot, checkout, base, commit, output] = process.argv.slice(2);
assert(output, 'Provide export, installed native package, previous export, checkout, base commit, commit and receipt path');
const exec = promisify(execFile);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const read = async file => { try { return await fs.readFile(file); } catch (error) { if (error.code === 'ENOENT') return null; throw error; } };
const blob = async name => hash(Buffer.from((await exec('git', ['show', `${commit}:${name}`], { cwd: checkout, encoding: 'buffer', maxBuffer: 1 << 26 })).stdout));
const changed = (await exec('git', ['diff', '--name-only', base, commit, '--', 'packages', 'self', 'server'], { cwd: checkout })).stdout.trim().split('\n').sort();
const payload = path.join(applicationRoot, '.firebase-hosting/reploid'), previousPayload = path.join(previousApplicationRoot, '.firebase-hosting/reploid');
const descriptor = JSON.parse(await fs.readFile(path.join(installedRoot, 'native-delivery.json')));
const packagedPaths = new Set(descriptor.entries.map(entry => entry.path));
const servedSet = new Set(JSON.parse(await fs.readFile(path.join(applicationRoot, 'self/config/browser-bundle-manifest.json'))).files.map(file => file.path));
const ASSETS = 'self/vendor/reploid/package-assets.json';
const REGENERATED = new Set(['self/config/module-inventory.json', 'self/config/vfs-manifest.json']);
const files = {};
for (const name of changed) {
  const expected = REGENERATED.has(name) ? hash(await fs.readFile(path.join(applicationRoot, name))) : await blob(name);
  const servedName = name.startsWith('self/') ? name.slice(5) : null;
  const served = servedName && await read(path.join(payload, servedName));
  const previous = servedName && await read(path.join(previousPayload, servedName));
  const packaged = await read(path.join(installedRoot, name));
  files[name] = { commitSha256: expected, ...(REGENERATED.has(name) ? { comparedWith: 'export regenerated copy' } : {}),
    served: servedName === null ? 'not a served path' : !servedSet.has(servedName) ? 'not in the served set' : served === null ? 'absent' : { path: servedName, sha256: hash(served), equalsCommit: hash(served) === expected,
      changedFromPreviousPayload: previous === null || hash(previous) !== hash(served) },
    packaged: packaged === null ? { present: false, inDescriptor: packagedPaths.has(name) }
      : { present: true, inDescriptor: packagedPaths.has(name), sha256: hash(packaged), equalsCommit: hash(packaged) === expected } };
}
const commitAssets = JSON.parse((await exec('git', ['show', `${commit}:${ASSETS}`], { cwd: checkout, maxBuffer: 1 << 26 })).stdout);
const servedAssets = JSON.parse(await fs.readFile(path.join(payload, ASSETS.slice(5))));
const entries = value => new Map((value.files || value.assets || value.entries || []).map(entry => [entry.path, entry]));
const [commitEntries, servedEntries] = [entries(commitAssets), entries(servedAssets)];
assert(servedEntries.size > 0 && commitEntries.size === servedEntries.size, 'Unexpected package asset listing shape');
const vendored = changed.filter(name => name.startsWith('self/vendor/reploid/') && name !== ASSETS).map(name => name.slice('self/vendor/reploid/'.length));
const assetEntries = Object.fromEntries(await Promise.all(vendored.map(async name => {
  const listed = servedEntries.get(name), blobHash = await blob('self/vendor/reploid/' + name);
  return [name, listed ? { listedSha256: listed.sha256, equalsCommit: listed.sha256 === blobHash } : 'not listed'];
})));
const differingEntries = [...servedEntries].filter(([name, entry]) => JSON.stringify(commitEntries.get(name)) !== JSON.stringify(entry)).map(([name]) => name);
const productSession = (await fs.readFile(path.join(payload, 'host/product-session.js'), 'utf8'));
const call = 'const requesterIdentity = () => swarm.partitions.requesterIdentity();';
const openings = (productSession.match(/(createChatSession|openCanonicalChatSession)\(\{[^}]*\}/g) || []);
const canonicalOpening = text => text.includes('canonical,') && text.includes('canonical.participantId');
const passesEverywhere = productSession.includes(call) && openings.length > 0
  && openings.every(text => canonicalOpening(text) || text.includes('requesterIdentity'));
const result = { schema: 'reploid.delivery-changed-file-check/v1', base, commit, changedFiles: changed, files,
  packageAssets: { changedVendoredEntries: assetEntries, entriesDifferingFromCommit: differingEntries },
  servedProductSessionPassesRequesterIdentity: passesEverywhere, requesterIdentityCall: call, chatOpeningCalls: openings.length, canonicalConfigurationOpeningsExempt: openings.filter(canonicalOpening).length,
  previousServedProductSessionPassedIt: (await fs.readFile(path.join(previousPayload, 'host/product-session.js'), 'utf8')).includes('requesterIdentity: () => swarm.partitions.requesterIdentity()') };
await fs.writeFile(output, JSON.stringify(result, null, 2) + '\n', { flag: 'wx' });
const rows = Object.values(files);
assert(Object.entries(files).every(([name, row]) => typeof row.served === 'string' ? row.served !== 'absent' : row.served.equalsCommit || name === ASSETS), 'Served copy differs from the commit or is absent');
assert(Object.values(assetEntries).every(entry => entry === 'not listed' || entry.equalsCommit), 'Package asset entry differs from the commit');
assert(differingEntries.every(name => name.startsWith('contracts/')), 'Package assets differ beyond the regenerated Doppler contract entries');
assert(rows.every(row => !row.packaged.present ? !row.packaged.inDescriptor : row.packaged.equalsCommit), 'Packaged copy differs from the commit');
assert(result.servedProductSessionPassesRequesterIdentity, 'Served product session does not pass requesterIdentity');
console.log(`${changed.length} changed files checked; served copies equal ${commit}; ${rows.filter(row => row.packaged.present).length} present in the native package`);
