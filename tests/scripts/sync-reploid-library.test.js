import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm, readdir } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { syncReploidLibrary } from '../../scripts/sync-reploid-library.js';

async function fixture(t) {
  const root = await mkdtemp(path.join(os.tmpdir(), 'reploid-library-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const source = path.join(root, 'packages/reploid/src');
  const output = path.join(root, 'shared/vendor/reploid');
  await mkdir(path.join(source, 'nested'), { recursive: true });
  await writeFile(path.join(source, '../package.json'), JSON.stringify({
    name: 'reploid', version: '0.1.0', exports: { '.': './src/index.js' }
  }));
  await writeFile(path.join(source, 'index.js'), 'export const value = 1;\n');
  await writeFile(path.join(source, 'nested/types.d.ts'), 'export declare const value: number;\n');
  await writeFile(path.join(source, 'nested/config.json'), '{"enabled":true}\n');
  await writeFile(path.join(source, 'CATSCAN.md'), 'Not a runtime asset.\n');
  return { root, source, output };
}

async function snapshot(directory) {
  const files = {};
  async function visit(relative = '') {
    for (const entry of await readdir(path.join(directory, relative), { withFileTypes: true })) {
      const name = path.join(relative, entry.name);
      if (entry.isDirectory()) await visit(name);
      else files[name] = (await readFile(path.join(directory, name))).toString('base64');
    }
  }
  await visit();
  return files;
}

test('sync and read-only check agree on generated bytes, metadata and nested assets', async t => {
  const { root, output } = await fixture(t);
  assert.equal(await syncReploidLibrary({ root }), 3);
  const before = await snapshot(output);
  assert.equal(await syncReploidLibrary({ root, check: true }), 3);
  assert.deepEqual(await snapshot(output), before);
  assert.equal('CATSCAN.md' in before, false);
  await syncReploidLibrary({ root });
  assert.deepEqual(await snapshot(output), before);
});

for (const kind of ['missing', 'changed', 'unexpected', 'metadata']) {
  test(`check rejects ${kind} mirror content without repairing or deleting it`, async t => {
    const { root, source, output } = await fixture(t);
    await syncReploidLibrary({ root });
    if (kind === 'missing') await rm(path.join(output, 'index.js'));
    if (kind === 'changed') await writeFile(path.join(source, 'index.js'), 'export const value = 2;\n');
    if (kind === 'unexpected') await writeFile(path.join(output, 'removed.js'), 'export {};\n');
    if (kind === 'metadata') await writeFile(path.join(output, 'package-assets.json'), '{}\n');
    const before = await snapshot(output);
    await assert.rejects(syncReploidLibrary({ root, check: true }), /assets are stale/);
    assert.deepEqual(await snapshot(output), before);
  });
}

test('check rejects an absent output tree without creating it', async t => {
  const { root, output } = await fixture(t);
  await assert.rejects(syncReploidLibrary({ root, check: true }), /missing: index.js/);
  await assert.rejects(readdir(output), { code: 'ENOENT' });
});
