#!/usr/bin/env node
/**
 * Assigns every file in the served browser tree to one owner:
 *   apps/poolday  the Poolday product (replo.id routes, its runtime and host composition)
 *   self          the agent/VFS substrate (Zero, X, kernel, tools, core)
 *   shared        files both of them load; shared files load only shared files
 *
 * Ownership follows references, not names. A file reachable from the product
 * entries and from the substrate entries is shared; otherwise it belongs to the
 * side that reaches it. Product traversal stops at the documented substrate entry
 * points. Files no entry reaches are assigned by the explicit rules below, each
 * with its reason. Writes docs/ownership-inventory.{json,md}; --check verifies them.
 */
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'acorn';
import { openBrowserTree, servedPathOf, rootOf, BROWSER_ROOTS } from '../server/browser-tree.js';
import { SELF_ENTRY_POINTS } from './verify-browser-boundaries.js';

export { SELF_ENTRY_POINTS };

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const JSON_OUTPUT = 'docs/ownership-inventory.json';
const MARKDOWN_OUTPUT = 'docs/ownership-inventory.md';
const posix = path.posix;

/** Poolday entry points: its HTML entries and the source of the product bundle. */
export const PRODUCT_ENTRIES = Object.freeze([
  'index.html', 'pool-entry.html', 'poolday-design.html', 'document-study.html', 'repair-smoke.html',
  'ui/pool-home/index.js'
]);

/** Substrate entry points beyond the module registry and Genesis file lists. */
const SUBSTRATE_ENTRIES = Object.freeze([
  'sw.js', 'sw-module-loader.js', 'bridge.js', 'runtime.js', 'manifest.js', 'tool-runner.js', 'boot-spec.js',
  'dream-instance.js', 'cloud-access.js', 'change-passport-entry.html', 'audit.html',
  'host/sw-module-loader.js', 'host/start-app.js', 'host/start-reploid.js', 'host/seed-vfs.js', 'host/vfs-bootstrap.js',
  'host/reploid-launch.js', 'entry/seed-vfs.js', 'entry/start-app.js', 'kernel/index.html', 'kernel/boot.js', 'zero/boot.js'
]);
/** Substrate components by charter: every file under these is a substrate entry. */
const SUBSTRATE_TREES = Object.freeze([
  'core/', 'tools/', 'kernel/', 'zero/', 'capsule/', 'boot-helpers/', 'lab/', 'testing/', 'personas/', 'prompts/',
  'experimental/', 'image/', 'ui/zero/', 'ui/proto/', 'ui/panels/', 'ui/change-passport/', 'shared/change-passport/', 'styles/proto/'
]);
/** The generated product bundle is built from this source entry. */
const GENERATED_FROM = Object.freeze({ 'ui/pool-home/app.bundle.js': ['ui/pool-home/index.js'] });
/**
 * Seed, copy and surface declaration lists name served paths as data for loaders
 * (VFS seeding, service-worker routing, surface resources). Their strings are not
 * dependencies of the declaring module; their imports still are.
 */
const DECLARATION_LISTS = new Set(['manifest.js', 'host/sw-module-loader.js', 'config/boot-seed.js', 'config/surface-resources.js',
  'config/surface-intents.js', 'config/self-source-catalog.json', 'config/self-source-manifest.json']);
/** Whole-tree descriptors list every served file; they are not references. */
const TREE_DESCRIPTORS = new Set(['config/browser-bundle-manifest.json', 'config/vfs-manifest.json', 'config/module-inventory.json']);

/** Files no entry reaches. First matching rule wins. */
const RULES = Object.freeze([
  { match: /^vendor\//, owner: 'shared', reason: 'Generated or integrity-verified package mirror delivered to every surface.' },
  { match: /^blueprints\/|^blueprint-index\.json$|^config\/blueprint-registry\.json$/, owner: 'self', reason: 'Substrate design records and their index.' },
  { match: /^config\/(module-registry|genesis-levels|genesis-template|zero-access)\.json$|^config\/zero-goals\.js$/, owner: 'self', reason: 'Substrate module registry, Genesis levels and Zero configuration.' },
  { match: /^config\/vfs-manifest\.json$|^config\/module-inventory\.json$/, owner: 'self', reason: 'Generated VFS hydration list and module inventory read by the substrate loader.' },
  { match: /^config\/browser-bundle-manifest\.json$/, owner: 'shared', reason: 'Generated byte manifest of the whole served tree; release identity for every surface.' },
  { match: /^ui\/(boot-home|boot-wizard|zero-home|reploid-home|shared)\/|^ui\/components\/vfs-progress\.js$/, owner: 'self', reason: 'Substrate boot and home screens seeded into the VFS by boot-seed profiles and the Zero self-source catalog.' },
  { match: /^capabilities\//, owner: 'self', reason: 'Optional agent capabilities (Optional Capabilities charter).' },
  { match: /^infrastructure\//, owner: 'self', reason: 'Runtime infrastructure charter; not loaded by the product.' },
  { match: /^styles\/audit\.css$/, owner: 'self', reason: 'Style of the substrate audit page.' },
  { match: /^(design|reset)\.html$/, owner: 'shared', reason: 'RD design-system specimen and storage reset page served for every surface; load only shared styles.' },
  { match: /^(pool|ui\/pool-home|ui\/poolday-design|styles\/poolday|host\/earning|host\/credits)\//, owner: 'apps/poolday', reason: 'Poolday runtime, interface and earning code used by hosted services, scripts and tests.' },
  { match: /^host\/(lora-training-worker|lora-training-executor|document-study)\.js$/, owner: 'apps/poolday', reason: 'Product worker and study page started by URL from product code.' },
  { match: /^config\/(model-manifests|model-pieces)\//, owner: 'shared', reason: 'Retained catalog data beside the shared catalog\'s manifests; the current catalog does not reference it.' },
  { match: /^config\/lora-adapters\//, owner: 'self', reason: 'Adapter manifests the substrate neural compiler reads from /config/lora-adapters.' },
  { match: /^config\/adapter-evaluations\//, owner: 'apps/poolday', reason: 'Held-out adapter evaluations read by product adapter evidence (host/adapter-evidence.js).' },
  { match: /^config\/document-comparison-sample\.json$/, owner: 'apps/poolday', reason: 'Fixture for the product document comparison.' },
  { match: /^providers\//, owner: 'self', reason: 'Model providers charter; not loaded by the product.' }
]);

const OWNERS = Object.freeze(['apps/poolday', 'self', 'shared']);

function jsReferences(code) {
  const relative = new Set(), absolute = new Set();
  let tree;
  try { tree = parse(code, { ecmaVersion: 'latest', sourceType: 'module', allowHashBang: true }); }
  catch {
    try { tree = parse(code, { ecmaVersion: 'latest', sourceType: 'script', allowHashBang: true }); }
    catch { return { relative, absolute, parsed: false }; }
  }
  const visit = node => {
    if (!node || typeof node !== 'object') return;
    if (node.type === 'Literal' && typeof node.value === 'string') {
      if (/^\.\.?\//.test(node.value)) relative.add(node.value);
      else if (/^\/[^/]/.test(node.value)) absolute.add(node.value);
    }
    if (node.type === 'TemplateElement' && /^\/[^/]/.test(node.value.cooked || '')) absolute.add(node.value.cooked);
    if (node.type === 'ImportExpression' && node.source?.type === 'TemplateLiteral' && !node.source.expressions.length) {
      relative.add(node.source.quasis[0].value.cooked);
    }
    for (const value of Object.values(node)) {
      if (Array.isArray(value)) value.forEach(visit);
      else if (value && typeof value === 'object' && value.type) visit(value);
    }
  };
  visit(tree);
  return { relative, absolute, parsed: true };
}

const stripSuffix = value => value.replace(/[?#].*$/, '');

export async function buildOwnershipInventory({ repoRoot = ROOT, why = false } = {}) {
  const tree = await openBrowserTree({ repoRoot });
  const files = tree.files;
  const has = served => tree.has(served);
  const servedUrl = value => {
    const clean = stripSuffix(value).replace(/^\/+/, '');
    if (has(clean)) return clean;
    if (clean.startsWith('self/') && has(clean.slice(5))) return clean.slice(5);
    return null;
  };
  const edges = new Map(files.map(name => [name, new Set()]));
  const add = (from, to) => { if (to && to !== from && has(to)) edges.get(from).add(to); };
  for (const served of files) {
    if (TREE_DESCRIPTORS.has(served) || served.startsWith('vendor/doppler/') || GENERATED_FROM[served]) {
      for (const target of GENERATED_FROM[served] || []) add(served, target);
      continue;
    }
    const sourcePath = tree.source(served);
    const ext = posix.extname(served);
    if (!['.js', '.mjs', '.html', '.css', '.json'].includes(ext)) continue;
    const text = await fs.readFile(path.join(repoRoot, sourcePath), 'utf8');
    const fromSource = value => {
      const target = posix.normalize(posix.join(posix.dirname(sourcePath), stripSuffix(value)));
      return servedPathOf(target);
    };
    const fromServed = value => (value.startsWith('/') ? servedUrl(value) : posix.normalize(posix.join(posix.dirname(served), stripSuffix(value))));
    if (ext === '.js' || ext === '.mjs') {
      const { relative, absolute } = jsReferences(text);
      for (const value of relative) add(served, fromSource(value));
      // A document URL in code is a navigation or cache target, not a dependency. Package
      // mirrors receive application URLs through configuration; their path strings are data.
      if (!DECLARATION_LISTS.has(served) && !served.startsWith('vendor/')) for (const value of absolute) if (!/\.html$/.test(stripSuffix(value))) add(served, servedUrl(value));
    } else if (ext === '.html') {
      // Loaded resources only: script/img sources and link hrefs. Anchors and <base> navigate.
      const loaded = [...text.matchAll(/\bsrc=["']([^"'#]+)["']/g), ...text.matchAll(/<link\b[^>]*\bhref=["']([^"'#]+)["']/g)];
      for (const match of loaded) {
        if (/^[a-z]+:/i.test(match[1]) || match[1].startsWith('//')) continue;
        add(served, fromServed(match[1]));
      }
      for (const block of text.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) {
        const { relative, absolute } = jsReferences(block[1]);
        for (const value of [...relative, ...absolute]) if (!/\.html$/.test(stripSuffix(value))) add(served, fromServed(value));
      }
    } else if (ext === '.css') {
      for (const match of text.matchAll(/url\(\s*["']?([^"')]+)["']?\s*\)|@import\s+["']([^"']+)["']/g)) {
        const value = match[1] || match[2];
        if (/^(data|https?):/.test(value)) continue;
        add(served, fromServed(value));
      }
    } else if (ext === '.json') {
      const visit = value => {
        if (typeof value === 'string' && value.startsWith('/')) add(served, servedUrl(value));
        else if (Array.isArray(value)) value.forEach(visit);
        else if (value && typeof value === 'object') Object.values(value).forEach(visit);
      };
      if (!DECLARATION_LISTS.has(served)) try { visit(JSON.parse(text)); } catch { /* Not JSON data. */ }
    }
  }

  const registry = JSON.parse(await fs.readFile(tree.absolute('config/module-registry.json'), 'utf8'));
  const genesis = JSON.parse(await fs.readFile(tree.absolute('config/genesis-levels.json'), 'utf8'));
  const substrateEntries = new Set(SUBSTRATE_ENTRIES.filter(has));
  for (const module of Object.values(registry.modules || registry)) for (const file of module.files || []) if (has(file)) substrateEntries.add(file);
  for (const list of Object.values(genesis.moduleFiles || {})) for (const file of list) if (has(file)) substrateEntries.add(file);
  for (const list of Object.values(genesis.sharedFiles || {})) for (const file of list) if (has(file)) substrateEntries.add(file);
  for (const level of Object.values(genesis.levelFiles || {})) for (const list of Object.values(level)) for (const file of list) if (has(file)) substrateEntries.add(file);
  for (const served of files) if (SUBSTRATE_TREES.some(prefix => served.startsWith(prefix))) substrateEntries.add(served);

  const reach = (entries, stopAt = new Set()) => {
    const seen = new Set(), stack = [...entries];
    while (stack.length) {
      const name = stack.pop();
      if (seen.has(name)) continue;
      seen.add(name);
      for (const target of edges.get(name) || []) if (!stopAt.has(target)) stack.push(target);
    }
    return seen;
  };
  const product = reach(PRODUCT_ENTRIES.filter(has), new Set(SELF_ENTRY_POINTS));
  const substrate = reach(substrateEntries);
  if (why) return { edges, productEntries: PRODUCT_ENTRIES.filter(has), substrateEntries: [...substrateEntries] };
  // Declarations, provenance records and vendored licenses describe one sibling module and follow its owner.
  const declarationSibling = served => served.replace(/\.d\.ts$|\.provenance\.json$/, '.js')
    .replace(/([^/]+)-LICENSE\.txt$/, (match, name) => `${name.toLowerCase()}.js`);

  const entries = [];
  for (const served of files) {
    let owner, basis;
    const subject = /\.d\.ts$|\.provenance\.json$|-LICENSE\.txt$/.test(served) && has(declarationSibling(served)) ? declarationSibling(served) : served;
    const inProduct = product.has(subject), inSubstrate = substrate.has(subject);
    if (served.startsWith('vendor/')) { owner = 'shared'; basis = RULES[0].reason; }
    else if (inProduct && inSubstrate) { owner = 'shared'; basis = 'Reached from product and substrate entries.'; }
    else if (inProduct) { owner = 'apps/poolday'; basis = 'Reached only from product entries.'; }
    else if (inSubstrate) { owner = 'self'; basis = 'Reached only from substrate entries.'; }
    else {
      const rule = RULES.find(item => item.match.test(served));
      owner = rule?.owner || null; basis = rule?.reason || null;
    }
    if (subject !== served && owner) basis = `Describes ${subject}. ${basis}`;
    entries.push({ served, source: tree.source(served), owner, basis });
  }
  // Directory notes belong to the owner of their directory. Charters are not served; they move with their directory.
  const byDirectory = new Map();
  for (const entry of entries) {
    if (/(^|\/)README\.md$/.test(entry.served)) continue;
    const directory = posix.dirname(entry.served);
    for (let dir = directory; ; dir = posix.dirname(dir)) {
      if (!byDirectory.has(dir)) byDirectory.set(dir, new Set());
      byDirectory.get(dir).add(entry.owner);
      if (dir === '.') break;
    }
  }
  for (const entry of entries) {
    if (!/(^|\/)README\.md$/.test(entry.served)) continue;
    const owners = [...(byDirectory.get(posix.dirname(entry.served)) || [])].filter(Boolean);
    if (owners.length === 1) { entry.owner = owners[0]; entry.basis = 'Note of a directory with one owner.'; }
    else {
      // A split directory's note stays with the substrate when it owns files there, else with the product.
      entry.owner = owners.includes('self') ? 'self' : owners.includes('apps/poolday') ? 'apps/poolday' : 'shared';
      entry.basis = `Note of a directory split among ${owners.sort().join(', ')}; it stays with ${entry.owner}.`;
    }
  }
  const unassigned = entries.filter(entry => !OWNERS.includes(entry.owner));
  if (unassigned.length) throw new Error(`Unassigned served files: ${unassigned.map(entry => entry.served).join(', ')}`);
  // Ownership must satisfy the boundary rules it is meant to establish.
  const ownerOf = new Map(entries.map(entry => [entry.served, entry.owner]));
  const violations = [];
  for (const [from, targets] of edges) {
    for (const to of targets) {
      const a = ownerOf.get(from), b = ownerOf.get(to);
      if (a === b || from.startsWith('vendor/')) continue;
      if (a === 'shared' || (a === 'self' && b === 'apps/poolday')
        || (a === 'apps/poolday' && b === 'self' && !SELF_ENTRY_POINTS.includes(to))) violations.push(`${from} (${a}) -> ${to} (${b})`);
    }
  }
  const location = entry => rootOf(entry.source);
  return {
    schema: 'reploid.ownership_inventory/v1',
    roots: BROWSER_ROOTS,
    productEntries: PRODUCT_ENTRIES, selfEntryPoints: SELF_ENTRY_POINTS,
    counts: Object.fromEntries(OWNERS.map(owner => [owner, entries.filter(entry => entry.owner === owner).length])),
    pendingMoves: entries.filter(entry => location(entry) !== entry.owner).length,
    violations,
    packageMirrors: { prefix: 'vendor/', owner: 'shared', basis: RULES[0].reason },
    // Package mirror files share one basis, stated once above.
    files: entries.map(entry => (entry.served.startsWith('vendor/') ? { served: entry.served, source: entry.source, owner: entry.owner } : entry))
  };
}

/** One shortest reference chain from each side's entries to a served path. */
export async function explainOwnership(target) {
  const { edges, productEntries, substrateEntries } = await buildOwnershipInventory({ why: true });
  const chain = (starts, stopAt = []) => {
    const previous = new Map(starts.map(start => [start, null])), queue = [...starts];
    while (queue.length) {
      const name = queue.shift();
      if (name === target) break;
      for (const next of edges.get(name) || []) if (!stopAt.includes(next) && !previous.has(next)) { previous.set(next, name); queue.push(next); }
    }
    if (!previous.has(target)) return null;
    const path = [];
    for (let name = target; name; name = previous.get(name)) path.unshift(name);
    return path;
  };
  return { product: chain(productEntries, SELF_ENTRY_POINTS), substrate: chain(substrateEntries) };
}

function renderMarkdown(inventory) {
  const lines = [
    '<!-- Generated by scripts/build-ownership-inventory.js. Do not edit directly. -->',
    '# Browser ownership inventory', '',
    'Every file in the served browser tree has one owner. The served URL of a file never',
    'depends on its owner: `server/browser-tree.js` composes `self/`, `shared/` and',
    '`apps/poolday/`, each holding files at their served paths, into one URL namespace.', '',
    '- **apps/poolday**: the Poolday product: replo.id routes, its runtime, host composition and interface.',
    '- **self**: the agent/VFS substrate: Zero, X, kernel, tools and core.',
    '- **shared**: files both load. Shared files reference only shared files.', '',
    'Ownership follows references: imports, HTML and CSS references, and absolute served URLs in code',
    'and JSON. A file reached from the product entries and the substrate entries is shared. Product',
    `traversal stops at the documented substrate entry point${inventory.selfEntryPoints.length > 1 ? 's' : ''} (${inventory.selfEntryPoints.map(name => `\`${name}\``).join(', ')}).`,
    'Files no entry reaches are assigned by the rules in the generator, with the reason shown.', '',
    `Product entries: ${inventory.productEntries.map(name => `\`${name}\``).join(', ')}.`, '',
    '| Owner | Files |', '| --- | ---: |',
    ...Object.entries(inventory.counts).map(([owner, count]) => `| ${owner} | ${count} |`),
    `| total | ${inventory.files.length} |`, '',
    inventory.pendingMoves
      ? `${inventory.pendingMoves} files still live outside their owner's root; the Source column shows where.`
      : 'Every file lives in its owner\'s root.', ''
  ];
  if (inventory.violations.length) lines.push('## Boundary conflicts', '', ...inventory.violations.map(item => `- ${item}`), '');
  const summary = new Map();
  for (const entry of inventory.files.filter(item => item.served.startsWith('vendor/'))) {
    const tree = entry.served.split('/').slice(0, 2).join('/') + '/';
    summary.set(tree, (summary.get(tree) || 0) + 1);
  }
  lines.push('## Package mirrors', '', 'Listed by tree; every file in each tree is shared. The JSON lists each file.', '',
    '| Served tree | Files | Owner |', '| --- | ---: | --- |',
    ...[...summary].map(([tree, count]) => `| \`${tree}\` | ${count} | shared |`), '');
  lines.push('## Files', '', '| Served path | Source | Owner | Basis |', '| --- | --- | --- | --- |');
  for (const entry of inventory.files.filter(item => !item.served.startsWith('vendor/'))) {
    lines.push(`| \`${entry.served}\` | \`${entry.source}\` | ${entry.owner} | ${entry.basis} |`);
  }
  return lines.join('\n') + '\n';
}

async function main() {
  const whyIndex = process.argv.indexOf('--why');
  if (whyIndex > 0) {
    const chains = await explainOwnership(process.argv[whyIndex + 1]);
    for (const [side, chain] of Object.entries(chains)) console.log(`${side}: ${chain ? chain.join(' -> ') : 'not reached'}`);
    return;
  }
  const check = process.argv.includes('--check');
  const inventory = await buildOwnershipInventory();
  const json = JSON.stringify(inventory, null, 2) + '\n', markdown = renderMarkdown(inventory);
  if (check) {
    const stale = [];
    for (const [file, content] of [[JSON_OUTPUT, json], [MARKDOWN_OUTPUT, markdown]]) {
      if (await fs.readFile(path.join(ROOT, file), 'utf8').catch(() => null) !== content) stale.push(file);
    }
    if (stale.length) throw new Error(`Ownership inventory is stale: ${stale.join(', ')}; run npm run build:ownership-inventory`);
    console.log(`[ownership] ${inventory.files.length} served files: ${Object.entries(inventory.counts).map(([o, n]) => `${o} ${n}`).join(', ')}`);
    return;
  }
  await fs.writeFile(path.join(ROOT, JSON_OUTPUT), json);
  await fs.writeFile(path.join(ROOT, MARKDOWN_OUTPUT), markdown);
  console.log(`[ownership] wrote ${inventory.files.length} files: ${Object.entries(inventory.counts).map(([o, n]) => `${o} ${n}`).join(', ')}; ${inventory.violations.length} conflicts`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error('[ownership]', error.message); process.exitCode = 1; });
}
