#!/usr/bin/env node
// Bundle the installed public validation API, never an independently authored option list.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packageArgument = process.argv.find(value => value.startsWith('--package-root='));
const packageRoot = resolve(packageArgument?.slice('--package-root='.length) || resolve(root, 'node_modules/doppler-gpu'));
const metadata = JSON.parse(await readFile(resolve(packageRoot, 'package.json'), 'utf8'));
const entry = metadata.exports?.['./generation-contract']?.import;
if (metadata.name !== 'doppler-gpu' || typeof entry !== 'string') {
  throw new Error('Installed Doppler must expose its public ./generation-contract; source-only option lists are not supported.');
}
const result = await build({ absWorkingDir: packageRoot, entryPoints: [resolve(packageRoot, entry)],
  bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2022', treeShaking: true });
const output = '// Generated by scripts/sync-doppler-generation-contract.js from installed doppler-gpu/generation-contract.\n'
  + result.outputFiles[0].text;
const provenance = `${JSON.stringify({ schema: 'reploid.doppler-generation-contract/v1', packageName: metadata.name,
  packageVersion: metadata.version, publicExport: './generation-contract',
  bundleSha256: createHash('sha256').update(output).digest('hex') }, null, 2)}\n`;
const declarations = await readFile(resolve(packageRoot, metadata.exports['./generation-contract'].types), 'utf8');
for (const [name, content] of [['doppler-generation-contract.js', output], ['doppler-generation-contract.d.ts', declarations], ['doppler-generation-contract.provenance.json', provenance]]) {
  const path = resolve(root, 'self/config', name);
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8') !== content) throw new Error(`${name} differs from the installed public generation API.`);
  } else await writeFile(path, content);
}
console.log('Doppler generation validation bundle matches the installed public API.');
